_FORMULA = re.compile(r"^[=+\-@\t\r]")


def _safe(df: pd.DataFrame) -> pd.DataFrame:
    """Neutralise spreadsheet formula injection in text cells."""
    out = df.copy()
    for c in out.columns:
        if out[c].dtype == object:
            out[c] = out[c].map(lambda v: "'" + v if isinstance(v, str) and _FORMULA.match(v) else v)
    return out


def export_workbook(state: dict, design: dict, results: pd.DataFrame | None, prior_meta: dict,
                    validation: str = "", priors_used: list | None = None) -> bytes:
    """priors_used defaults to the table saved with the last estimate (state["result"]["info"])."""
    if priors_used is None:
        priors_used = ((state.get("result") or {}).get("info") or {}).get("priors_used")
    inputs = state.get("inputs", {})
    search = state.get("search", {})
    sample = state.get("sample", {})
    items = sample.get("items", [])
    labels, llm, ft = state.get("labels", {}), state.get("llm", {}), state.get("fulltext", {})
    outcomes = [o["name"] for o in parse_outcomes(inputs.get("outcomes_text", ""))]
    n_lab, _ = label_progress(items, labels)
    meta_rows = [
        ("생성 시각", _dt.datetime.now().isoformat(timespec="seconds")),
        ("PICO", pico_text(inputs)), ("제외 기준", inputs.get("exclusion", "")),
        ("outcomes", inputs.get("outcomes_text", "")), ("임계 k", inputs.get("threshold")),
        ("PubMed 검색식", inputs.get("q_pubmed", "")), ("Europe PMC 검색식", inputs.get("q_epmc", "")),
        ("OpenAlex 검색식", inputs.get("q_openalex", "")),
        ("건수만 입력한 DB", json.dumps(parse_count_only(inputs.get("count_only")), ensure_ascii=False)),
    ]
    for d in search.get("dbs", []):
        meta_rows.append((f"검색 결과: {d.get('db')}", f"hits {d.get('count')}, 수집 {d.get('fetched')}, "
                          f"partial={d.get('partial')}; {'; '.join(d.get('notes') or [])}"))
    meta_rows += [
        ("업로드 레코드", search.get("n_upload", 0)), ("고유 N (중복 제거 후)", search.get("n_unique")),
        ("건수만 DB 추가분 (mean, sd)", json.dumps(search.get("extra_N"))),
        ("층별 N", json.dumps(sample.get("strata_N", {}))),
        ("설계 (design_default.json)", json.dumps({k: design.get(k) for k in
                                                  ("n_total", "census_top", "bounds", "phase2", "phase1_frac",
                                                   "decision", "threshold", "cap", "date", "validated")},
                                                 ensure_ascii=False)),
        ("난수 시드", state.get("seed")), ("판정 완료 표본 수", n_lab),
        ("priors 버전 (sha256)", prior_meta.get("version")), ("priors 날짜", prior_meta.get("date")),
        ("검증 성적", validation),
    ]
    meta = pd.DataFrame(meta_rows, columns=["항목", "값"])
    meta["값"] = meta["값"].map(lambda v: "" if v is None else str(v))

    srows = []
    for it in items:
        s = llm.get(it["rid"]) or {}
        srows.append({"rid": it["rid"], "phase": it.get("phase"), "stratum": it["stratum"], "title": it["title"],
                      "abstract": it["abstract"], "doi": it.get("doi"), "pmid": it.get("pmid"),
                      "year": it.get("year"), "source_db": it.get("source_db"), "label": labels.get(it["rid"], ""),
                      "llm_suggestion": s.get("decision", ""), "llm_reason": s.get("reason", ""),
                      "llm_evidence": s.get("evidence", "")})
    frows = []
    for it in passers(items, labels):
        d = ft.get(it["rid"], {}) or {}
        row = {"rid": it["rid"], "title": it["title"], "doi": it.get("doi"), "decision": d.get("decision") or "미판정",
               "fulltext_source": d.get("source", ""), "fetch_note": d.get("reason", "")}
        for o in outcomes:
            v = (d.get("quant") or {}).get(o)
            row[f"{o} 정량"] = {True: "있음", False: "없음"}.get(v, "미확정")
            det = (d.get("detect") or {}).get(o) or {}
            row[f"{o} 탐지"] = det.get("status", "")
            row[f"{o} 근거"] = " | ".join(det.get("evidence") or [])
        frows.append(row)
    ko, en = methods_paragraph({"design": design, "dbs": [d.get("db") for d in search.get("dbs", [])],
                                "n_unique": int(search.get("n_unique") or 0), "n_labelled": n_lab,
                                "seed": state.get("seed"), "priors_version": prior_meta.get("version"),
                                "top_N": (sample.get("strata_N") or {}).get("S1"),
                                "threshold": inputs.get("threshold")})
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        _safe(meta).to_excel(xw, sheet_name="실행정보", index=False)
        _safe(pd.DataFrame(srows)).to_excel(xw, sheet_name="표본판정", index=False)
        _safe(pd.DataFrame(frows)).to_excel(xw, sheet_name="전문판정", index=False)
        _safe(results if results is not None else pd.DataFrame()).to_excel(xw, sheet_name="결과", index=False)
        _safe(pd.DataFrame(priors_used or [])).to_excel(xw, sheet_name="사전분포", index=False)
        pd.DataFrame({"언어": ["한국어", "English"], "방법론": [ko, en]}).to_excel(xw, sheet_name="방법론", index=False)
    return buf.getvalue()
