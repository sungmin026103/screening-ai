# ---------------------------------------------------------------- design / inputs
def load_design(path=None) -> dict:
    """design_default.json read at call time (it may be regenerated by the replay CLI)."""
    try:
        raw = json.loads(Path(path or DESIGN_PATH).read_text(encoding="utf-8"))
        if not isinstance(raw, dict):
            raise ValueError
    except Exception:
        return dict(_FALLBACK_DESIGN, _fallback=True)
    return {**_FALLBACK_DESIGN, **raw}


def priors_info(path=None) -> dict:
    p = Path(path or PRIORS_PATH)
    if not p.exists():
        return {"path": str(p), "version": "default (priors.json 없음)", "date": ""}
    data = p.read_bytes()
    return {"path": p.name, "version": hashlib.sha256(data).hexdigest()[:12],
            "date": _dt.datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d")}


def parse_outcomes(text: str) -> list[dict]:
    """One outcome per line, optional 'name: syn1, syn2'. Blank/duplicate names dropped (case-insensitive)."""
    out, seen = [], set()
    for line in (text or "").splitlines():
        line = line.strip().lstrip("-•*").strip()
        if not line:
            continue
        name, _, syn = line.partition(":")
        name = name.strip()
        if not name or name.lower() in seen or name == INCLUDED:
            continue
        seen.add(name.lower())
        syns = [s.strip() for s in re.split(r"[,;]", syn) if s.strip()]
        out.append({"name": name, "synonyms": syns})
    return out


def parse_count_only(rows) -> dict:
    """[{name, count}] -> {name: int>0}; rows with no name or a non-positive/invalid count are skipped."""
    out = {}
    for r in rows or []:
        name = str((r or {}).get("name") or "").strip()
        try:
            c = int(float((r or {}).get("count") or 0))
        except (TypeError, ValueError):
            continue
        if name and c > 0:
            out[name] = out.get(name, 0) + c
    return out


def pico_text(inputs: dict) -> str:
    parts = [("P", inputs.get("P")), ("I", inputs.get("I")), ("C", inputs.get("C")), ("O", inputs.get("O"))]
    return "\n".join(f"{k}: {str(v).strip()}" for k, v in parts if v and str(v).strip())


def pico_from_project(p: dict) -> dict:
    p = p or {}
    return {"P": p.get("population", ""), "I": p.get("intervention", ""), "C": p.get("comparator", ""),
            "O": p.get("outcome", ""), "exclusion": p.get("exclusion_criteria", "")}


def input_problems(inputs: dict) -> list[str]:
    """Reasons the search / sampling steps cannot run yet (empty list = ready)."""
    probs = []
    if not pico_text(inputs):
        probs.append("PICO가 비어 있습니다 (P·I·C·O 중 하나 이상 입력).")
    if not parse_outcomes(inputs.get("outcomes_text", "")):
        probs.append("outcome을 한 줄에 하나 이상 입력하세요.")
    return probs


def new_state(seed: int | None = None) -> dict:
    if seed is None:
        seed = int(np.random.SeedSequence().generate_state(1)[0] % 2**31)
    return {"inputs": {}, "search": {}, "seed": int(seed), "sample": {}, "labels": {}, "llm": {},
            "fulltext": {}, "result": {}}


# ---------------------------------------------------------------- sampling
def initial_n(design: dict) -> int:
    n = int(design.get("n_total", 150))
    if design.get("phase2"):
        n = int(round(float(design.get("phase1_frac", 0.7)) * n))
    return max(n, 1)


def stratify(records: pd.DataFrame, pico: str, bounds) -> tuple[np.ndarray, np.ndarray]:
    """PICO relevance strata. Scored WITHOUT exclusion text, exactly as the replay validation and the
    library prior fit do (validated pipeline parity)."""
    scores = relevance_scores(records, pico)
    return scores, make_strata(scores, tuple(bounds))


def relevance_warning(scores, tol: float = 1e-6) -> str | None:
    """Relevance scores (almost) all equal -> stratification is meaningless. Typical cause: PICO in
    Korean against English records (TF-IDF shares no terms)."""
    s = np.asarray(scores, dtype=float)
    if s.size < 2 or float(np.nanstd(s)) > tol:
        return None
    return ("PICO 관련도 점수가 거의 모두 같아(분산 ≈ 0) 관련도 층화가 작동하지 않습니다. 레코드가 영어라면 "
            "PICO를 영어로 입력하세요 (「① 입력」 수정 후 「표본 다시 뽑기」).")


def stratum_counts(strata) -> dict:
    names, c = np.unique(np.asarray(strata).astype(str), return_counts=True)
    return {str(k): int(v) for k, v in sorted(zip(names, c), key=lambda t: (len(t[0]), t[0]))}


def _cell(v) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return ""
    return str(v).strip()


def sample_items(records: pd.DataFrame, idx, strata, phase: int) -> list[dict]:
    items = []
    for i in np.asarray(idx, dtype=int):
        r = records.iloc[int(i)]
        items.append({"rid": str(int(i)), "idx": int(i), "stratum": str(strata[int(i)]), "phase": int(phase),
                      **{k: _cell(r.get(k)) for k in ("title", "abstract", "doi", "pmid", "pmcid", "year",
                                                       "source_db")}})
    return items


def draw_initial(records: pd.DataFrame, strata, design: dict, seed: int) -> list[dict]:
    alloc = allocate(np.asarray(strata), initial_n(design), int(design.get("census_top", 100)))
    idx = draw_sample(np.asarray(strata), alloc, int(seed))
    return sample_items(records, idx, strata, 1)


def stratum_obs(strata_N: dict, items: list[dict], labels: dict) -> list[StratumObs]:
    """n = labelled sampled records per stratum; x = O + ? (every "?" goes forward to full text, see
    passers, so it is a stage-1 pass)."""
    out = []
    for h, N in strata_N.items():
        lab = [labels.get(it["rid"]) for it in items if it["stratum"] == h]
        lab = [v for v in lab if v in LABELS]
        out.append(StratumObs(h, int(N), len(lab), float(sum(LABEL_WEIGHT[v] for v in lab))))
    return out


def label_progress(items: list[dict], labels: dict) -> tuple[int, int]:
    return sum(labels.get(it["rid"]) in LABELS for it in items), len(items)


def stratum_table(strata_N: dict, items: list[dict], labels: dict) -> pd.DataFrame:
    rows = []
    for o in stratum_obs(strata_N, items, labels):
        k = sum(1 for it in items if it["stratum"] == o.name)
        rows.append({"층": o.name, "모집단 N": o.N, "표본": k, "판정 완료": o.n, "통과(O + ?)": o.x,
                     "통과율": (o.x / o.n) if o.n else float("nan")})
    return pd.DataFrame(rows)


def followup(strata, items: list[dict], labels: dict, strata_N: dict, n_add: int, seed: int,
             records: pd.DataFrame) -> tuple[dict, list[dict]]:
    """Neyman allocation of n_add extra labels over not-yet-sampled records (phase 2)."""
    obs = stratum_obs(strata_N, items, labels)
    # cap by records not yet drawn (labelled or not), so a stratum is never over-drawn
    drawn = {h: sum(1 for it in items if it["stratum"] == h) for h in strata_N}
    obs_cap = [StratumObs(o.name, o.N - drawn[o.name] + o.n, o.n, o.x) for o in obs]
    alloc = neyman_followup(obs_cap, int(n_add))
    masked = np.asarray(strata).astype(object).copy()
    masked[[it["idx"] for it in items]] = "_sampled"
    idx = draw_sample(masked.astype(str), {k: v for k, v in alloc.items() if v > 0}, int(seed))
    phase = max([it.get("phase", 1) for it in items] or [1]) + 1
    return alloc, sample_items(records, idx, strata, phase)


# ---------------------------------------------------------------- full text
def passers(items: list[dict], labels: dict) -> list[dict]:
    return [it for it in items if labels.get(it["rid"]) in PASS_LABELS]


def suggest_quant(detect: dict) -> dict:
    """detect_quant results -> suggested yes(True)/no(False); None when nothing was detected."""
    out = {}
    for o, d in (detect or {}).items():
        st_ = (d or {}).get("status")
        out[o] = True if st_ == "likely" else (False if st_ == "not_found" else None)
    return out


def fulltext_obs(items: list[dict], labels: dict, ft: dict, outcome_names: list[str]):
    """FulltextObs from saved decisions plus bookkeeping.

    Passers without a decision are counted as missing (interval widens) and reported as pending;
    an included paper whose per-outcome flag is unconfirmed counts as 'no data' and is reported.
    """
    m_read = y = m_missing = pending = 0
    quant = {o: 0 for o in outcome_names}
    q_pending = {o: 0 for o in outcome_names}
    for it in passers(items, labels):
        d = ft.get(it["rid"], {}) or {}
        dec = d.get("decision")
        if dec == FT_INCLUDE:
            m_read += 1
            y += 1
            for o in outcome_names:
                v = (d.get("quant") or {}).get(o)
                if v is True:
                    quant[o] += 1
                elif v is None:
                    q_pending[o] += 1
        elif dec == FT_EXCLUDE:
            m_read += 1
        else:
            m_missing += 1
            if dec != FT_MISSING:
                pending += 1
    quant[INCLUDED] = y
    info = {"m_read": m_read, "y_include": y, "m_missing": m_missing, "pending": pending,
            "quant_pending": {o: c for o, c in q_pending.items() if c}}
    return FulltextObs(m_read, y, m_missing, quant), info


# ---------------------------------------------------------------- estimation
def estimator_priors(priors: dict, outcome_names: list[str], design: dict) -> dict:
    """replay.outcome_priors (q3 resolved per outcome + "_included" prior) with the design's cutoffs."""
    pri = outcome_priors(priors, list(outcome_names))
    dec = design.get("decision") or priors.get("decision") or (0.8, 0.2)
    return {**pri, "decision": tuple(float(x) for x in dec)}


def min_sr_note(design: dict) -> str:
    """q3_min_sr needs the SR library to recount families; the page only has priors.json, which
    replay --full writes AFTER replay.q3_with_min_sr, so the filter is already baked in."""
    m = int(design.get("q3_min_sr") or 0)
    if m <= 0:
        return "q3_min_sr = 0 (적용 없음)"
    return (f"q3_min_sr = {m}: 라이브러리 없이 priors.json만 사용 — replay --full이 저장 시 "
            f"q3_with_min_sr를 적용했으므로 그대로 사용(재검증 불가)")


def _beta_row(stage, key, p) -> dict:
    a, b = float(p.a), float(p.b)
    return {"stage": stage, "key": key, "a": a, "b": b, "mean": a / (a + b)}


SMALL_CONC = 2.0 + 1e-6   # beta_mom's fallback concentration (a+b = 2): < 2 SR values or no usable variance


def q3_note(family: str, p, family_priors: dict) -> str:
    """Audit note for a q3 prior: flag a family prior fitted from a single SR (beta_mom fallback,
    a+b = 2) and outcomes that fell back to the pooled _default prior."""
    if family not in family_priors:
        return "패밀리 사전분포 없음 → _default(전체 outcome 합산) 사용"
    if float(p.a) + float(p.b) <= SMALL_CONC:
        return ("a+b = 2 (적률 추정 대체값): 이 패밀리는 단일 SR(또는 분산 추정 불가)에서 온 약한 사전분포 — "
                "해석 주의")
    return ""


def priors_used_table(pri: dict, strata_names, outcome_names, design: dict, threshold: int,
                      priors_q3: dict | None = None) -> list[dict]:
    """Every prior parameter and setting the estimator actually used (audit sheet rows).
    priors_q3: the raw family-level q3 priors (priors.json), used for the single-SR note."""
    rows = []
    spec = pri["stratum"]
    for h in strata_names:
        p = spec if isinstance(spec, StagePrior) else (spec.get(h) or spec["_default"]) \
            if isinstance(spec, dict) else spec(h, 0.0)
        rows.append(_beta_row("stratum (z1 pass rate)", h, p))
    rows.append(_beta_row("q2 (included | full text)", "q2", pri["q2"]))
    q3 = pri["q3"]
    fam_q3 = (priors_q3 or {}) if isinstance(priors_q3, dict) else {}
    for o in list(outcome_names) + [INCLUDED]:
        p = q3 if isinstance(q3, StagePrior) else (q3.get(o) or q3["_default"])
        key = INCLUDED_LABEL if o == INCLUDED else f"{o} [{outcome_family(o)}]"
        row = _beta_row("q3 (quant data | included)", key, p)
        if o != INCLUDED:
            row["note"] = q3_note(outcome_family(o), p, fam_q3)
        rows.append(row)
    rows.append(_beta_row("r_study", "r_study", pri["r_study"]))
    dec = pri["decision"]
    rows += [{"stage": "decision", "key": "go if P(k>=t) >=", "a": float(dec[0])},
             {"stage": "decision", "key": "no-go if P(k>=t) <=", "a": float(dec[1])},
             {"stage": "threshold", "key": "t", "a": float(threshold)},
             {"stage": "design", "key": json.dumps({k: design.get(k) for k in
                                                    ("n_total", "census_top", "bounds", "phase2", "phase1_frac",
                                                     "decision", "threshold", "cap", "q3_min_sr", "date",
                                                     "validated")}, ensure_ascii=False)},
             {"stage": "q3_min_sr", "key": min_sr_note(design)}]
    return rows


def run_estimate(strata_N: dict, items: list[dict], labels: dict, ft: dict, outcome_names: list[str],
                 priors: dict, design: dict, threshold: int, extra_N=None, seed: int = 0,
                 n_draws: int = 10000) -> tuple[pd.DataFrame, dict]:
    obs = stratum_obs(strata_N, items, labels)
    ft_obs, info = fulltext_obs(items, labels, ft, outcome_names)
    pri = estimator_priors(priors, outcome_names, design)
    ex = tuple(float(v) for v in extra_N) if extra_N and float(extra_N[0]) > 0 else None
    res = estimate_k(obs, ft_obs, list(outcome_names) + [INCLUDED], pri, threshold=int(threshold),
                     n_draws=int(n_draws), seed=int(seed), extra_N=ex)
    res["family"] = [outcome_family(o) if o != INCLUDED else "-" for o in res["outcome"]]
    res["outcome"] = res["outcome"].replace({INCLUDED: INCLUDED_LABEL})
    info["n_labelled"] = sum(o.n for o in obs)
    info["decision_cut"] = list(pri["decision"])
    info["priors_used"] = priors_used_table(pri, list(strata_N), outcome_names, design, threshold,
                                            priors_q3=priors.get("q3"))
    return res, info


def recommend_more(strata_N: dict, items: list[dict], labels: dict, n_add: int = 50) -> dict:
    """Suggested extra labels per stratum (Neyman) for a borderline call."""
    obs = stratum_obs(strata_N, items, labels)
    drawn = {h: sum(1 for it in items if it["stratum"] == h) for h in strata_N}
    obs_cap = [StratumObs(o.name, o.N - drawn[o.name] + o.n, o.n, o.x) for o in obs]
    return {k: v for k, v in neyman_followup(obs_cap, n_add).items() if v > 0}


GATE_CSV = PKG.parent / "docs" / "validation" / "replay_nested_gate.csv"
FRAGILE_MARGIN = 0.02    # accuracy within 2 points of the acceptance bar is reported as fragile


def _gate_from_csv(path=None) -> dict:
    """n_sr / n_units / SR-equal accuracy from the nested-LOSO gate CSV (fallback for designs written
    before these fields were stored in design_default.json)."""
    try:
        df = pd.read_csv(Path(path or GATE_CSV))
        g = df.groupby("sr_id")[["n_called", "n_correct"]].sum()
        g = g[g["n_called"] > 0]
        return {"n_sr": int(df["sr_id"].nunique()), "n_units": int(len(df[["sr_id", "outcome"]].drop_duplicates())),
                "acc_sr": float((g["n_correct"] / g["n_called"]).mean()) if len(g) else None}
    except Exception:
        return {}


def validation_badge(design: dict, threshold: int | None = None, count_only: bool = False,
                     gate_csv=None) -> tuple[bool, str]:
    """(in_validated_scope, text). False -> show as a warning: not validated, or the run uses a
    threshold other than the validated one, or a count-only DB (not part of the replay)."""
    if not design.get("validated") or design.get("_fallback"):
        return False, "미검증 추정 — 재연 검증을 통과한 기본 설계가 없습니다."
    m = dict(design.get("metrics_real_nested") or design.get("metrics_real") or {})
    if any(m.get(k) is None for k in ("n_sr", "acc_sr")):
        m = {**_gate_from_csv(gate_csv), **{k: v for k, v in m.items() if v is not None}}
    n_sr = m.get("n_sr") or len(design.get("srs") or [])
    pct = lambda v: f"{100 * float(v):.0f}%" if v is not None else "?"  # noqa: E731
    units = f", outcome {m['n_units']}개" if m.get("n_units") else ""
    text = (f"과거 {n_sr}개 SR (outcome k가 있는 SR{units}) 재연 검증: 80% 구간 포함률 {pct(m.get('cov80'))}, "
            f"판정 정확도 {pct(m.get('acc'))} (보류 {pct(m.get('abstain'))})")
    caveat = [f"SR 동일가중 정확도 {pct(m.get('acc_sr'))}", f"보류 비율 {pct(m.get('abstain'))}"]
    if m.get("acc") is not None and float(m["acc"]) - ACCEPT["acc"] < FRAGILE_MARGIN:
        caveat.append(f"정확도가 기준선({pct(ACCEPT['acc'])}) 근처(취약)")
    text += "\n\n주의: " + " · ".join(caveat) + "."
    t_valid = int(design.get("threshold", 5))
    out_of_scope = []
    if threshold is not None and int(threshold) != t_valid:
        out_of_scope.append(f"최소 연구 수 k = {int(threshold)} (검증은 k = {t_valid})")
    if count_only:
        out_of_scope.append("건수만 입력한 DB 사용")
    if out_of_scope:
        return False, text + "\n\n이 설정은 재연 검증 범위 밖: " + ", ".join(out_of_scope) + "."
    return True, text


def census_sentence(top_N, census_top) -> tuple[str, str]:
    """Top stratum: up to census_top records are labelled; a full census only when N_S1 <= census_top."""
    c = int(census_top or 0)
    if top_N is None:
        return (f"상위 층(S1)은 최대 {c}건을 판정하고(S1이 {c}건 이하일 때만 전수),",
                f"up to {c} top-stratum (S1) records were screened (a full census only when S1 held "
                f"{c} or fewer records)")
    n = int(top_N)
    if n <= c:
        return (f"상위 층(S1) {n:,}건은 전수 판정하고,", f"all {n:,} top-stratum (S1) records were screened (census)")
    return (f"상위 층(S1) {n:,}건 중 {c}건을 무작위로 판정하고(전수 아님),",
            f"{c} of {n:,} top-stratum (S1) records were screened at random (not a census)")


